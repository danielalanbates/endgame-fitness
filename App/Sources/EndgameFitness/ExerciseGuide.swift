//  lifts, drills, warm-ups, ramp-up sets, cardio, intervals and rest-day
//  recovery. Written for this app (no text copied from other sources),
//  deterministic and local.
//
//  `ExerciseGuide.directions(for:libraryID:)` is the one lookup the UI uses.
//  It combines this guide with the bundled exercise library: a good library
//  match supplies the detailed steps and muscles, the guide supplies the
//  one-line cue, the safety cue and the easier/harder options. The guide's own
//  steps are used when the library has no entry, an empty one, or one for a
//  different movement (`preferOverLibrary`).
//

import Foundation

/// What the UI shows for one exercise.
struct ExerciseDirections: Equatable {
    enum Kind: Equatable { case lift, drill, warmup, cardio, recovery }

    var name: String
    var kind: Kind
    /// One short line for lists (Today card, rest day, program days).
    var cue: String
    var steps: [String]
    var safety: String
    var easier: String?
    var harder: String?
    /// The library entry behind the steps (or shown alongside them), if any.
    var libraryID: String?
    var stepsFromLibrary: Bool
    /// The guide's short steps, kept when the detailed steps come from the library.
    var quickSteps: [String]

    /// The first steps for an inline "How to" (short ones first).
    var inlineSteps: [String] { Array((quickSteps.isEmpty ? steps : quickSteps).prefix(2)) }

    /// Plain-language effort note for lifts ("2-3 reps short of failure").
    var effortNote: String? { kind == .lift ? ExerciseGuide.effortNote : nil }
}

enum ExerciseGuide {
    struct Entry {
        let names: [String]
        let kind: ExerciseDirections.Kind
        let cue: String
        let steps: [String]
        let safety: String
        let easier: String
        let harder: String
        /// The library's entry for this name is a different variation (or empty).
        var preferOverLibrary = false
    }

    static let effortNote = "How hard: stop each working set with 2-3 good reps still left in you (RPE 7-8, also called 2-3 reps in reserve). The last reps should feel slow and hard, but look exactly like the first one. If your form changes, the set is over, even if you could grind out more."

    static let genericSafety = "Use a load you can control through the whole movement. Stop if you feel sharp or joint pain."

    // MARK: Lookup

    /// The guide key for a program item: the scheme, "Warm-up:"/"Optional:"
    /// prefixes and parenthetical doses removed, ramp-up and practice sets
    /// mapped to their shared guide, then library-style normalisation.
    static func key(for raw: String) -> String {
        var n = ProgramTargetParser.parse(raw).name.trimmingCharacters(in: .whitespaces)
        for prefix in ["optional:", "warm-up:", "warm up:", "warmup:"] where n.lowercased().hasPrefix(prefix) {
            n = String(n.dropFirst(prefix.count)).trimmingCharacters(in: .whitespaces)
        }
        let lower = n.lowercased()
        if lower.hasPrefix("ramp-up sets") || lower.hasPrefix("ramp up sets") { return "ramp up set" }
        if lower.hasPrefix("practice set") { return "practice set" }
        // "VO2max Intervals: 4 min hard / 3 min easy (...)": the name is before the colon.
        if let colon = n.firstIndex(of: ":") { n = String(n[..<colon]) }
        n = n.replacingOccurrences(of: #"\s*\([^)]*\)"#, with: "", options: .regularExpression)
        return ExerciseLibrary.normalize(n)
    }

    static let byKey: [String: Entry] = {
        var map: [String: Entry] = [:]
        for e in entries {
            for name in e.names {
                let k = key(for: name)
                if map[k] == nil { map[k] = e }
                let compact = k.replacingOccurrences(of: " ", with: "")
                if map[compact] == nil { map[compact] = e }
            }
        }
        return map
    }()

    static func entry(for name: String) -> Entry? {
        let k = key(for: name)
        guard !k.isEmpty else { return nil }
        return byKey[k] ?? byKey[k.replacingOccurrences(of: " ", with: "")]
    }

    /// The lift a "Ramp-up Sets for X" / "Practice Set of X" warm-up builds to.
    static func warmupTarget(of raw: String) -> String? {
        let n = ProgramTargetParser.parse(raw).name
        for marker in ["Ramp-up Sets for ", "Practice Set of "] {
            guard let r = n.range(of: marker) else { continue }
            var rest = String(n[r.upperBound...])
            if let p = rest.range(of: " (") { rest = String(rest[..<p.lowerBound]) }
            return rest.trimmingCharacters(in: .whitespaces)
        }
        return nil
    }

    /// Directions for `name`, or nil when neither the guide nor the library knows it.
    static func directions(for name: String, libraryID: String? = nil) -> ExerciseDirections? {
        let display = ProgramTargetParser.parse(name).name
        let guide = entry(for: name)
        // Warm-ups, cardio and recovery items are never library lifts.
        let liftLike = guide.map { $0.kind == .lift || $0.kind == .drill } ?? true
        let lib: LibraryExercise? = liftLike
            ? (libraryID.flatMap { ExerciseLibrary.shared.entry(id: $0) } ?? ExerciseLibrary.shared.match(name: display))
            : nil
        let libSteps = lib?.instructions.filter { !$0.trimmingCharacters(in: .whitespaces).isEmpty } ?? []
        let libraryUsable = lib != nil && !libSteps.isEmpty && !(guide?.preferOverLibrary ?? false)

        if let guide {
            var steps = guide.steps
            // A ramp-up / practice set names its lift.
            if let target = warmupTarget(of: name), !target.isEmpty {
                steps = steps.map { $0.replacingOccurrences(of: "your first lift", with: target) }
            }
            return ExerciseDirections(name: display, kind: guide.kind, cue: guide.cue,
                                      steps: libraryUsable ? libSteps : steps, safety: guide.safety,
                                      easier: guide.easier, harder: guide.harder,
                                      libraryID: libraryUsable ? lib?.id : nil, stepsFromLibrary: libraryUsable,
                                      quickSteps: libraryUsable ? steps : [])
        }
        guard let lib, !libSteps.isEmpty else { return nil }
        let kind: ExerciseDirections.Kind = lib.tracking == .timed
            ? (lib.category == "cardio" ? .cardio : .drill) : .lift
        return ExerciseDirections(name: display, kind: kind, cue: shortCue(libSteps[0]), steps: libSteps,
                                  safety: genericSafety, easier: nil, harder: nil, libraryID: lib.id,
                                  stepsFromLibrary: true, quickSteps: [])
    }

    /// One-line cue for a list row (the guide's cue, else the first library step, shortened).
    static func cue(for name: String) -> String? { directions(for: name)?.cue }

    /// First sentence of a step, cut to about 90 characters on a word boundary.
    static func shortCue(_ step: String) -> String {
        var s = step.trimmingCharacters(in: .whitespaces)
        if let dot = s.range(of: ". ") { s = String(s[..<dot.lowerBound]) }
        if s.hasSuffix(".") { s.removeLast() }
        guard s.count > 90 else { return s }
        let cut = s.prefix(90)
        return (cut.range(of: " ", options: .backwards).map { String(cut[..<$0.lowerBound]) } ?? String(cut)) + "…"
    }

    // MARK: - Entries

    private static func lift(_ names: [String], cue: String, steps: [String], safe: String, easier: String, harder: String,
                             prefer: Bool = false) -> Entry {
        Entry(names: names, kind: .lift, cue: cue, steps: steps, safety: safe, easier: easier, harder: harder, preferOverLibrary: prefer)
    }

    private static func drill(_ names: [String], cue: String, steps: [String], safe: String, easier: String, harder: String,
                              prefer: Bool = false) -> Entry {
        Entry(names: names, kind: .drill, cue: cue, steps: steps, safety: safe, easier: easier, harder: harder, preferOverLibrary: prefer)
    }

    private static func warm(_ names: [String], cue: String, steps: [String], safe: String, easier: String, harder: String) -> Entry {
        Entry(names: names, kind: .warmup, cue: cue, steps: steps, safety: safe, easier: easier, harder: harder)
    }

